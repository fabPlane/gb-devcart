POWER_IN = ("VCC", "VDD", "VSS", "GND", "VCCA", "VCCB")
def ptype(v):
    w = v.split()[0]
    if w == "VOUT":
        return "power_out"
    return "power_in" if w in POWER_IN else "passive"

