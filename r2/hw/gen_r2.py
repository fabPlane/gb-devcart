def esc(n: str) -> str:
    return n.replace("#", "").replace("/", "_")

def sym(prefix, desc, pins, left=None):
    """pins: [(num, name, type)]; left: names on the left side (rest go right)."""
    if left is None:
        half = (len(pins) + 1) // 2
        L, R = pins[:half], pins[half:]
    else:
        L = [p for p in pins if p[1] in left]
        R = [p for p in pins if p[1] not in left]
    return (prefix, desc, L, R)

