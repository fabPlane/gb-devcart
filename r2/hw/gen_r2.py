comps, PARTOF, nets, PLACE = [], {}, {}, {}

def add(ref, part, value=None, at=None, **fields):
    f = dict(fields)
    if part in MPN:
        f.update(MPN=MPN[part][0], Manufacturer=MPN[part][1], LCSC=MPN[part][2])
    elif part in ("R", "C") and value in PASSIVE:
        f["LCSC"] = PASSIVE[value]
    comps.append({"ref": ref, "value": value or part, "footprint": FP[part],
                  "fields": f, "libSource": {"lib": "gbdev2", "part": part}})
    PARTOF[ref] = part
    if at:
        PLACE[ref] = at

def pin(ref, name):
    nums = PINNO[PARTOF[ref]][name]
    return [(ref, n) for n in nums]

def conn(net, *ends):
    lst = nets.setdefault(net, [])
    for ref, name in ends:
        for r, n in pin(ref, name):
            lst.append({"ref": r, "pin": n})

